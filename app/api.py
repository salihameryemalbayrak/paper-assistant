"""HTTP API for the answer chain (FastAPI).

    POST /ask     {"question": "..."} -> answer, its kind, cited sources, checks, timing
    GET  /health  is the API up and is the vector index reachable?
    GET  /docs    interactive documentation, generated by FastAPI from the models below

The chain (embedding model, retriever, LLM client) is built once at startup in the
lifespan hook, not per request. /ask is a plain `def`: chain.invoke is synchronous, so
FastAPI runs it in a worker thread and other requests are not blocked meanwhile.

Usage:
    uv run uvicorn app.api:app --port 8000      # then http://localhost:8000/docs
"""

import time
from collections.abc import Callable
from contextlib import asynccontextmanager
from dataclasses import dataclass, field
from typing import Any

from fastapi import FastAPI, HTTPException
from langchain_core.runnables import Runnable
from pydantic import BaseModel, Field, field_validator

from app.ask import CONTEXT_K, answer_kind, build_chain, check_citations, citation_label


class AskRequest(BaseModel):
    question: str = Field(
        min_length=1, max_length=1000, examples=["QLoRA belleği nasıl azaltıyor?"]
    )

    @field_validator("question")
    @classmethod
    def _not_blank(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("question is blank")
        return value.strip()


class Source(BaseModel):
    """One chunk given to the LLM, under the label the answer cites."""

    label: str  # e.g. "[ragas, s.3, §3]"
    paper: str
    pages: list[int]
    section: str
    chunk_id: str
    text: str
    url: str | None  # the paper's PDF opened at the cited page, e.g. ...pdf/2305.14314v1#page=2


class AskResponse(BaseModel):
    question: str
    answer: str
    kind: str  # "answer" | "partial" | "refusal" (app.ask.answer_kind)
    query_en: str | None  # the English translation, if the retriever uses one
    sources: list[Source]
    invented_citations: list[str]  # cited labels that were not in the context
    seconds: float
    llm: str
    retriever: str


@dataclass
class Engine:
    """What the API needs; tests pass a fake one (fake LLM and retriever)."""

    chain: Runnable  # question -> {"question", "query", "docs", "answer"}
    llm: str
    retriever: str
    health: Callable[[], dict[str, Any]]
    callbacks: list  # tracing handlers (app.tracing), [] when tracing is off
    arxiv_ids: dict[str, str] = field(default_factory=dict)  # paper -> pinned arXiv id


PDF_URL = "https://arxiv.org/pdf/{arxiv_id}#page={page}"  # #page=N: browsers' PDF viewers


def pdf_url(arxiv_ids: dict[str, str], paper: str, page: int) -> str | None:
    arxiv_id = arxiv_ids.get(paper)
    return PDF_URL.format(arxiv_id=arxiv_id, page=page) if arxiv_id else None


def build_engine() -> Engine:
    """The real chain, configured from app.config (same as `python -m app.ask`)."""
    from app.config import get_settings
    from app.llm import get_chat_model
    from app.retrieval import build_retriever, needs_translation
    from app.tracing import get_callbacks
    from app.translate import build_translator
    from app.truecase import load_vocabulary
    from app.vectorstore import get_vectorstore
    from ingest.download import SOURCES_FILE, parse_sources

    s = get_settings()
    llm = get_chat_model(s)
    retriever = build_retriever(
        s.retriever, CONTEXT_K, reranker=s.reranker, candidates=s.rerank_candidates,
        depth=s.retrieval_depth,
    )  # fmt: skip
    translator = (
        build_translator(get_chat_model(s, s.translate_model or None))
        if needs_translation(s.retriever, s.reranker)
        else None
    )

    def health() -> dict[str, Any]:
        store = get_vectorstore()
        return {"chunks": store.client.get_collection(store.collection_name).points_count}

    return Engine(
        chain=build_chain(retriever, llm, translator, load_vocabulary()),
        llm=s.llm_model,
        retriever=s.retriever + (f" + rerank {s.reranker}" if s.reranker else ""),
        health=health,
        callbacks=get_callbacks(s),
        arxiv_ids={
            src.short_name: src.arxiv_id
            for src in parse_sources(SOURCES_FILE.read_text(encoding="utf-8"))
        },
    )


def create_app(engine_factory: Callable[[], Engine] = build_engine) -> FastAPI:
    @asynccontextmanager
    async def lifespan(app: FastAPI):
        app.state.engine = engine_factory()  # loads the embedding model once
        yield

    app = FastAPI(title="Paper assistant", version="0.1.0", lifespan=lifespan)

    @app.get("/health")
    def health() -> dict[str, Any]:
        try:
            return {"status": "ok", **app.state.engine.health()}
        except Exception as e:  # Qdrant down or collection missing
            raise HTTPException(503, f"vector index unreachable: {type(e).__name__}") from e

    @app.post("/ask")
    def ask(request: AskRequest) -> AskResponse:
        from openai import APIConnectionError, APITimeoutError

        from app.tracing import trace_config

        engine: Engine = app.state.engine
        config = trace_config(engine.callbacks, name="api ask", tags=["api", engine.retriever])
        start = time.perf_counter()
        try:
            out = engine.chain.invoke(request.question, config=config)
        except (APIConnectionError, APITimeoutError) as e:
            raise HTTPException(503, f"LLM server unreachable: {type(e).__name__}") from e
        seconds = time.perf_counter() - start
        # No flush() here: Langfuse sends traces from a background thread on its own. A
        # flush would make the request wait for the upload, and retry for ~7 s per
        # request when Langfuse is down (measured, D45). The CLI flushes because it exits.
        answer = out["answer"].strip()
        return AskResponse(
            question=request.question,
            answer=answer,
            kind=answer_kind(answer),
            query_en=out["query"].get("en"),
            sources=[
                Source(
                    label=citation_label(d.metadata),
                    paper=d.metadata["paper"],
                    pages=d.metadata["pages"],
                    section=d.metadata["section"],
                    chunk_id=d.metadata["chunk_id"],
                    text=d.metadata["text"],
                    url=pdf_url(engine.arxiv_ids, d.metadata["paper"], d.metadata["pages"][0]),
                )
                for d in out["docs"]
            ],
            invented_citations=check_citations(answer, out["docs"]),
            seconds=round(seconds, 2),
            llm=engine.llm,
            retriever=engine.retriever,
        )

    return app


app = create_app()  # what `uvicorn app.api:app` serves
