"""Generate the secrets for the local Langfuse (infra/docker-compose.obs.yml).

Writes infra/.env (read by docker compose for variable substitution; git-ignored) and
adds the three settings the app needs to the project .env:
LANGFUSE_PUBLIC_KEY, LANGFUSE_SECRET_KEY, LANGFUSE_BASE_URL.

Never overwrites an existing infra/.env: the databases keep the passwords they were
created with, and new ones would lock Langfuse out of its own data. Prints no secrets.

Usage:
    uv run python infra/make_secrets.py
"""

import secrets
import sys
from pathlib import Path

INFRA_ENV = Path(__file__).parent / ".env"
APP_ENV = Path(__file__).parent.parent / ".env"
LOGIN_EMAIL = "admin@example.com"  # local login only; example.com is reserved for examples


def generate() -> dict[str, str]:
    def password() -> str:
        return secrets.token_urlsafe(24)

    return {
        "POSTGRES_PASSWORD": password(),
        "CLICKHOUSE_PASSWORD": password(),
        "REDIS_AUTH": password(),
        "MINIO_ROOT_PASSWORD": password(),
        "SALT": password(),
        "NEXTAUTH_SECRET": password(),
        "ENCRYPTION_KEY": secrets.token_hex(32),  # 256-bit key as 64 hex chars (Langfuse docs)
        "LANGFUSE_PUBLIC_KEY": f"pk-lf-{secrets.token_hex(16)}",
        "LANGFUSE_SECRET_KEY": f"sk-lf-{secrets.token_hex(16)}",
        "LANGFUSE_INIT_USER_EMAIL": LOGIN_EMAIL,
        "LANGFUSE_INIT_USER_PASSWORD": password(),
    }


def main() -> None:
    if INFRA_ENV.exists():
        sys.exit(f"{INFRA_ENV} exists; keeping it (new passwords would not match the data).")
    values = generate()
    INFRA_ENV.write_text(
        "# Generated by infra/make_secrets.py. Local Langfuse secrets: never commit.\n"
        + "".join(f"{k}={v}\n" for k, v in values.items()),
        encoding="utf-8",
    )
    INFRA_ENV.chmod(0o600)  # readable by this user only

    app_lines = {
        "LANGFUSE_PUBLIC_KEY": values["LANGFUSE_PUBLIC_KEY"],
        "LANGFUSE_SECRET_KEY": values["LANGFUSE_SECRET_KEY"],
        "LANGFUSE_BASE_URL": "http://localhost:3000",
    }
    existing = APP_ENV.read_text(encoding="utf-8") if APP_ENV.exists() else ""
    if any(line.startswith("LANGFUSE_") for line in existing.splitlines()):
        print(f"{APP_ENV} already has LANGFUSE_* settings: not changed. Copy the keys by hand.")
    else:
        with APP_ENV.open("a", encoding="utf-8") as f:
            f.write("\n# Local Langfuse (infra/make_secrets.py)\n")
            f.write("".join(f"{k}={v}\n" for k, v in app_lines.items()))
        print(f"added LANGFUSE_PUBLIC_KEY, LANGFUSE_SECRET_KEY, LANGFUSE_BASE_URL to {APP_ENV}")
    print(f"wrote {INFRA_ENV} (login: {LOGIN_EMAIL}, password: see LANGFUSE_INIT_USER_PASSWORD)")


if __name__ == "__main__":
    main()
